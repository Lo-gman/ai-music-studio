"""
AI Music Studio - Video Production.
Renders audio-reactive 16:9 MP4 videos using the visualizer module.
Each video has unique animated visuals driven by the music's spectrum.
"""

import os
import subprocess
import argparse

from visualizer import render_video


def write_video_metadata(out_path, meta):
    """Write title, description, tags for YouTube upload."""
    base = os.path.splitext(out_path)[0]
    title = f"{meta.get('title', 'Quiet Frequencies')} - {meta.get('category', 'Ambient').title()} Music"
    description = f"""{meta.get('description', 'Original instrumental ambient soundscape.')}

Original instrumental ambient soundscape procedurally generated by Quiet Frequencies.
No paid AI music APIs used. No third-party audio samples. All assets original.

Length: {meta.get('minutes', 5)} minutes
Category: {meta.get('category', 'Ambient')}
Style: {meta.get('style', 'ambient')}
Seed: {meta.get('seed', 0)}

Synthetic Content Disclosure: This video contains procedurally generated
audio and visuals created with original code. No AI music-generation APIs
were used. No third-party stock footage or audio samples.

#ambient #focusmusic #relaxingmusic #sleepmusic #studymusic #quietfrequencies #backgroundmusic #originalmusic
"""
    tags = "ambient, focus music, relaxing music, sleep music, study music, quiet frequencies, background music, original music"

    with open(base + ".title.txt", "w", encoding="utf-8") as f:
        f.write(title)
    with open(base + ".description.txt", "w", encoding="utf-8") as f:
        f.write(description)
    with open(base + ".tags.txt", "w", encoding="utf-8") as f:
        f.write(tags)
    return title, description, tags


def render_video_from_audio(audio_path, cover_path, out_path, style, title,
                            minutes=None, seconds=None):
    """Render a full audio-reactive video."""
    return render_video(
        wav_path=audio_path,
        cover_path=cover_path,
        out_path=out_path,
        style=style,
        title=title,
        seconds=seconds,
    )


def main():
    p = argparse.ArgumentParser(description="Render an audio-reactive music video")
    p.add_argument("--audio", required=True, help="Path to WAV audio file")
    p.add_argument("--cover", required=True, help="Path to cover JPG image")
    p.add_argument("--out", required=True, help="Output MP4 path")
    p.add_argument("--style", required=True,
                   choices=["deep_focus", "lofi_instrumental", "piano_ambient",
                            "concentration", "deep_sleep", "soft_piano",
                            "rain_atmosphere", "ocean_nature",
                            "relaxing_electronic", "lofi_chill",
                            "dreamy_ambient", "jazzy_background"])
    p.add_argument("--title", required=True, help="Video title")
    p.add_argument("--minutes", type=int, default=None,
                   help="Target video length in minutes (uses full audio if omitted)")
    p.add_argument("--short", type=int, default=None,
                   help="Render short test video (seconds)")
    args = p.parse_args()

    seconds = args.short
    if args.minutes and not args.short:
        seconds = args.minutes * 60

    render_video_from_audio(args.audio, args.cover, args.out, args.style,
                            args.title, seconds=seconds)
    meta = {"title": args.title, "category": "ambient",
            "style": args.style, "minutes": args.minutes or 5}
    write_video_metadata(args.out, meta)
    print(f"Rendered {args.out}")


if __name__ == "__main__":
    main()
